const { test }=require('node:test');
const assert=require('node:assert/strict');
const jwt=require('jsonwebtoken');
const rows=new Map([['users:SENTINEL',{collection:'users',id:'SENTINEL',data:{id:'SENTINEL',role:'superAdmin'}}]]);
async function query(sql,args) {
  if (/SELECT collection/.test(sql)) return {rows:[...rows.values()]};
  if (/INSERT INTO ndfa_docs/.test(sql)) rows.set(`${args[0]}:${args[1]}`,{collection:args[0],id:args[1],data:JSON.parse(args[2])});
  return {rows:[]};
}
require.cache[require.resolve('../src/lib/pg')]={exports:{query,getPool:()=>({connect:async()=>({query,release(){}})})}};
const db=require('../src/lib/db');
test('Developer onboarding, permission boundaries, expiry, rotation and revocation',async t=>{
  await db.initDb();
  db.upsert('users',{id:'SA',role:'superAdmin',isActive:true});
  db.upsert('users',{id:'ADMIN',role:'admin',companyId:'ONE',isActive:true});
  db.upsert('companies',{id:'ONE',isActive:true,modules:{customers:true}});
  db.upsert('companies',{id:'TWO',isActive:true});
  db.upsert('customers',{id:'C1',companyId:'ONE',name:'Allowed',password:'hidden',faceDescriptor:[1]});
  db.upsert('customers',{id:'C2',companyId:'TWO',name:'Private'});
  const server=require('../src/app').listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  t.after(()=>new Promise(r=>server.close(r)));
  const {jwtSecret}=require('../src/config/env');
  const sa=jwt.sign({userId:'SA'},jwtSecret), staff=jwt.sign({userId:'ADMIN'},jwtSecret);
  async function call(path,method='GET',body,token) {
    const r=await fetch(`http://127.0.0.1:${server.address().port}/api/v1${path}`,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:`Bearer ${token}`}:{})},body:body===undefined?undefined:JSON.stringify(body)});
    return {status:r.status,headers:r.headers,...await r.json()};
  }
  const application={name:'Developer',email:'dev@example.test',organization:'Example',purpose:'Reporting',scopes:['customers:read'],requestedDays:30,consent:true};
  assert.equal((await call('/developer/applications','POST',{...application,consent:false})).status,400);
  assert.equal((await call('/developer/applications','POST',{...application,scopes:['users:write']})).status,400);
  const pending=await call('/developer/applications','POST',application);assert.equal(pending.status,201);
  const id=pending.data.id;
  assert.equal((await call('/developer/manage')).status,401);
  assert.equal((await call('/developer/manage','GET',undefined,staff)).status,403);
  assert.equal((await call('/developer/manage','GET',undefined,sa)).status,200);
  const approval={companyId:'ONE',scopes:['customers:read'],days:30,requestsPerMinute:2};
  assert.equal((await call(`/developer/manage/applications/${id}/approve`,'POST',{...approval,days:0},sa)).status,400);
  const issued=await call(`/developer/manage/applications/${id}/approve`,'POST',approval,sa);assert.equal(issued.status,201,issued.message);
  let token=issued.data.token;const grantId=issued.data.grant.id;
  assert.ok(token.startsWith('ndfa_'));assert.equal(issued.data.grant.tokenHash,undefined);
  const overview=await call('/developer/manage','GET',undefined,sa);
  assert.ok(!JSON.stringify(overview).includes(token));assert.ok(!JSON.stringify(overview).includes('tokenHash'));
  assert.equal((await call(`/developer/manage/applications/${id}/approve`,'POST',approval,sa)).status,404);
  assert.equal((await call('/developer/data/customers','GET',undefined,staff)).status,401);
  assert.equal((await call('/auth/me','GET',undefined,token)).status,401);
  assert.equal((await call('/developer/manage','GET',undefined,token)).status,401);
  assert.equal((await call('/developer/data/employees','GET',undefined,token)).status,403);
  const result=await call('/developer/data/customers?companyId=TWO','GET',undefined,token);
  assert.deepEqual(result.data.items,[{id:'C1',name:'Allowed'}]);
  assert.equal((await call('/developer/data/customers?limit=101','GET',undefined,token)).status,400);
  const capped=await call('/developer/data/customers','GET',undefined,token);assert.equal(capped.status,429);assert.equal(capped.headers.get('Retry-After'),'60');
  const rotated=await call(`/developer/manage/grants/${grantId}/rotate`,'POST',{},sa);assert.equal(rotated.status,201);
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,401);token=rotated.data.token;
  db.upsert('companies',{...db.findById('companies','ONE'),modules:{customers:false}});
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,403);
  db.upsert('companies',{...db.findById('companies','ONE'),modules:{customers:true},actions:{customers:{export:false}}});
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,403);
  db.upsert('companies',{...db.findById('companies','ONE'),actions:{customers:{export:true}}});
  db.upsert('companies',{...db.findById('companies','ONE'),modules:{customers:true},isActive:false});
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,403);
  db.upsert('companies',{...db.findById('companies','ONE'),isActive:true});
  db.upsert('apiGrants',{...db.findById('apiGrants',grantId),expiresAt:new Date(0).toISOString()});
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,401);
  assert.equal((await call(`/developer/manage/grants/${grantId}/rotate`,'POST',{},sa)).status,409);
  db.upsert('apiGrants',{...db.findById('apiGrants',grantId),expiresAt:new Date(Date.now()+86400000).toISOString(),requestsPerMinute:10});
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,200);
  assert.equal((await call(`/developer/manage/grants/${grantId}/revoke`,'POST',{},sa)).status,200);
  assert.equal((await call('/developer/data/customers','GET',undefined,token)).status,401);
  const reject=await call('/developer/applications','POST',application);
  assert.equal((await call(`/developer/manage/applications/${reject.data.id}/reject`,'POST',{},sa)).status,200);
  await call('/developer/applications','POST',application);
  const limited=await call('/developer/applications','POST',application);assert.equal(limited.status,429);
  assert.ok(db.getCollection('platformAudit').some(a=>a.action==='api.key.revoked'));
  await db.flush();
});
